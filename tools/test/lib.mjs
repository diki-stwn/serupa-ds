// Shared helpers for the Serupa test suite.
import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const HERE = path.dirname(fileURLToPath(import.meta.url));
export const PROJECT = path.resolve(process.env.SERUPA_PROJECT || path.join(HERE, '..', '..'));
export const read = (p) => fs.readFileSync(path.join(PROJECT, p), 'utf8');
export const tokens = () => JSON.parse(read('tokens.json'));

const first = (v) => (v && typeof v === 'object' ? Object.values(v)[0] : v);
const ref = (v) => String(v).replace(/^\{(.+)\}$/, 'var(--$1)');

// tokens.json -> CSS, the same variables tokens.css defines (built from the source, so the
// tests also cover token edits before tokens.css is regenerated by npm run tokens).
export function tokensCss(t = tokens()) {
  const themes = Object.keys(t.color.tokens.find((x) => x.value && typeof x.value === 'object' && Object.keys(x.value).length > 1).value);
  let root = '';
  for (const [, g] of Object.entries(t)) {
    if (!g || !Array.isArray(g.tokens)) continue;
    for (const x of g.tokens) root += `--${x.name.replace(/[\\.]/g, '\\$&')}:${ref(first(x.value))};`;
  }
  for (const [k, v] of Object.entries(t.type.families)) root += `--font-${k}:${v};`;
  let css = (t.type.fonts || []).map((f) => `@font-face{font-family:"${f.family}";src:url("${path.join(PROJECT, f.file)}") format("woff2");font-weight:${f.weight};font-style:${f.style};font-display:block}`).join('');
  css += `:root{${root}}`;
  for (const th of themes) {
    css += `[data-theme="${th}"]{` + t.color.tokens.filter((x) => x.value && typeof x.value === 'object' && x.value[th] != null && Object.keys(x.value).length > 1).map((x) => `--${x.name}:${ref(x.value[th])};`).join('') + '}';
  }
  return { css, themes };
}

// A page with the tokens, bundle.css and (optionally) React + serupa.iife.js, written next to the
// project so file:// URLs to fonts and libraries resolve.
export function writePage(name, body, { react = false, extraHead = '', base = false, theme = false, htmlAttrs = null, bundle = '../dist/bundle.css' } = {}) {
  const dir = path.join(PROJECT, '.test-tmp');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'tokens.test.css'), tokensCss().css);
  const libs = react ? ['dist/lib/react.production.min.js', 'dist/lib/react-dom.production.min.js', 'dist/serupa.iife.js'].map((s) => `<script src="../${s}"></script>`).join('') : '';
  const attrs = htmlAttrs ?? `data-theme="${tokensCss().themes[0]}"`;
  const head = (theme ? '<script src="../dist/theme.js"></script>' : '') + '<link rel="stylesheet" href="tokens.test.css">' + (base ? '<link rel="stylesheet" href="../dist/base.css">' : '') + `<link rel="stylesheet" href="${bundle}">`;
  const html = `<!doctype html><html ${attrs}><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">${head}${libs}${extraHead}</head><body>${body}</body></html>`;
  const file = path.join(dir, name);
  fs.writeFileSync(file, html);
  return 'file://' + file;
}
export function cleanup() { fs.rmSync(path.join(PROJECT, '.test-tmp'), { recursive: true, force: true }); }

// Which engine the Playwright suites run in: SERUPA_BROWSER=chromium (default) | firefox | webkit.
// Baselines are kept per engine (Chromium's are the reference; tools/test/compat.mjs compares engines).
export const ENGINE = process.env.SERUPA_BROWSER || 'chromium';
export const suffix = ENGINE === 'chromium' ? '' : '-' + ENGINE;
export async function browser() {
  /** @type {Record<string, import('playwright').BrowserType>} */
  let pw;
  try { pw = /** @type {any} */ (await import('playwright')); } catch { fail(`Install Playwright first: npm i -D playwright && npx playwright install ${ENGINE}`); }
  if (!pw[ENGINE]) fail(`Unknown SERUPA_BROWSER "${ENGINE}" (chromium, firefox or webkit)`);
  // Headless Firefox finds no pointing device and reports (hover: none), so hover styles behind
  // @media (hover: hover) never apply. Give it a desktop's fine, hovering pointer (2 | 4).
  const opts = ENGINE === 'firefox' ? { firefoxUserPrefs: { 'ui.primaryPointerCapabilities': 6, 'ui.allPointerCapabilities': 6 } } : {};
  try { return await pw[ENGINE].launch(opts); } catch (e) { fail(`Can't start ${ENGINE}: run "npx playwright install ${ENGINE}".\n${e.message.split('\n')[0]}`); }
}

// Under Vitest (npm run test:checks) each result is a test of its own, so the reporter lists it with the component
// tests and -t picks one out; run with node, a suite prints its results and exits with whether they passed.
const vt = process.env.VITEST ? await import('vitest') : null;

export function report(name, results) {
  if (vt) {
    vt.describe(name, () => { for (const r of results) vt.test(r.name, () => { if (!r.ok) throw new Error(r.detail || 'failed'); }); });
    return true;
  }
  const failed = results.filter((r) => !r.ok);
  for (const r of results) console.log(`${r.ok ? 'PASS' : 'FAIL'}  ${r.name}${r.ok || !r.detail ? '' : '\n      ' + r.detail}`);
  console.log(`\n${name}: ${results.length - failed.length}/${results.length} passed`);
  return failed.length === 0;
}

// Serves a built folder (storybook-static/) over http on a free port: Storybook's iframe loads its modules with
// fetch, which file:// URLs refuse. Returns the base URL and close().
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.woff2': 'font/woff2', '.svg': 'image/svg+xml', '.png': 'image/png' };
export function serve(dir) {
  const server = http.createServer((req, res) => {
    const f = path.join(dir, decodeURIComponent(new URL(req.url, 'http://x').pathname));
    if (!f.startsWith(dir) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); res.end(); return; }
    res.writeHead(200, { 'content-type': TYPES[path.extname(f)] || 'application/octet-stream' });
    fs.createReadStream(f).pipe(res);
  }).listen(0);
  return { base: `http://127.0.0.1:${/** @type {import('node:net').AddressInfo} */ (server.address()).port}`, close: () => server.close() };
}

// The end of a suite run with node: exit 0 if it passed. Under Vitest, which owns the process, a failed result is
// already a failed test.
export function done(ok) { if (!vt) process.exit(ok ? 0 : 1); }

// A suite that can't run at all (nothing built, a tool missing): a failed test under Vitest, else exit 1.
export function fail(message) {
  if (vt) throw new Error(message);
  console.log('FAIL  ' + message);
  process.exit(1);
}

// The project a suite checks: the folder given after the script (node tools/test/foundation.mjs <dir>), or this one.
export const projectArg = () => path.resolve((!vt && process.argv[2]) || PROJECT);
