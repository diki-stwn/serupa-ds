// The icons the components draw themselves, taken from src/material/icons.ts:
// - src/material/builtin.ts: one named export per icon a component imports (`import * as icons from
//   "../../material/builtin"`, then `icons.Close`), so a bundler keeps only the icons the imported components draw.
//   They render at once and on the server.
// - src/material/named.ts: the same icons in one list, a separate chunk that Icon loads the first time a page draws
//   one of these names as a string (`<Icon name="close" />`), before falling back to the full set.
//   node tools/icons/builtin.mjs           write both (after a component starts using a new icon)
//   node tools/icons/builtin.mjs --check   exit 1 if either is out of date (the Icon names test runs this)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const P = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(P, 'src', 'material', 'builtin.ts');
const NAMED = path.join(P, 'src', 'material', 'named.ts');
const HEAD = '/* Generated by tools/icons/builtin.mjs from src/material/icons.ts (Material Symbols Rounded, Apache 2.0); run it, don\'t edit this. */\n'
  + 'import type { IconData } from "./types";\n\n';

export function builtin() {
  // The table is cut into parts (src/material/part/), which icons.ts re-exports.
  const PART = path.join(P, 'src', 'material', 'part');
  const table = fs.readdirSync(PART).sort().map((f) => fs.readFileSync(path.join(PART, f), 'utf8')).join('');
  const icons = new Map([...table
    .matchAll(/export const (\w+): IconData = \{ name: "([a-z0-9_]+)", d: "([^"]+)"/g)].map((m) => [m[1], { name: m[2], d: m[3] }]));
  const keep = new Set();
  const unknown = [];
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const f = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== 'material') scan(f); continue; }
      if (!/\.tsx?$/.test(e.name) || /\.(stories|test)\./.test(e.name)) continue;
      const src = fs.readFileSync(f, 'utf8');
      if (!/import \* as icons from "[./]+material\/builtin"/.test(src)) continue;
      for (const m of src.matchAll(/\bicons\.([A-Z]\w*)/g)) {
        if (icons.has(m[1])) keep.add(m[1]);
        else unknown.push(`${path.relative(P, f)}: icons.${m[1]} isn't a Material Symbol`);
      }
    }
  };
  scan(path.join(P, 'src'));
  const names = [...keep].sort();
  const text = HEAD
    + '/* The icons the components draw themselves. Components import them by name, so each bundle keeps only its own. */\n'
    + names.map((n) => `export const ${n}: IconData = { name: "${icons.get(n).name}", d: "${icons.get(n).d}" };\n`).join('');
  const named = HEAD
    + '/** The icons the components draw, by name: loaded the first time a page draws one of these names as a string. */\n'
    + 'export const NAMED_ICONS: readonly IconData[] = [\n'
    + names.map((n) => `  { name: "${icons.get(n).name}", d: "${icons.get(n).d}" },\n`).join('') + '];\n';
  return { names, text, named, unknown };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { names, text, named, unknown } = builtin();
  if (unknown.length) { console.log(unknown.join('\n')); process.exit(1); }
  if (process.argv.includes('--check')) {
    const read = (f) => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '');
    const ok = read(OUT) === text && read(NAMED) === named;
    console.log(ok ? `Built-in icons are up to date (${names.length})` : 'src/material/builtin.ts or named.ts is out of date: run node tools/icons/builtin.mjs');
    process.exit(ok ? 0 : 1);
  }
  fs.writeFileSync(OUT, text);
  fs.writeFileSync(NAMED, named);
  console.log(`Wrote src/material/builtin.ts and named.ts (${names.length} built in)`);
}
