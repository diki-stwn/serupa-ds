// The lists every component used to be added to by hand, built from the component folders instead, so a pull
// request that adds a component only touches its own folder (and two of them never conflict over a shared list).
// Writes src/generated/ (not committed, like src/styles/utilities.css):
//   components.ts    export * from each src/components/<Name>/index.ts (src/index.ts re-exports it)
//   globals.ts       ComponentGlobals: those values by name, for window.Serupa's type on plain pages
//   components.css   @import of each <Name>.css, in the order of src/styles/cascade.txt, then the rest A to Z
//   status.ts        each component that isn't stable (alpha, beta or deprecated, from the doc comment on its
//                    export), for the docs pages
//   tested.ts        each component's test names, grouped as its <Name>.test.tsx groups them, for the "What the
//                    tests check" part of its docs page (docs/blocks.tsx)
//   labels.ts        each component's own words (src/components/<Name>/labels.ts: <Name>Labels, en, id), merged into one English and
//                    one Indonesian set (src/internal/labels.ts adds the shared ones)
// The build, Storybook, Vitest, typecheck and lint run it first: node tools/build/registry.mjs.
// It also keeps the components index in README.md (between the components:start and components:end comments): each
// component under its Storybook group, with the first sentence of its guide. tools/release.mjs rewrites it on each
// release pull request, so it can't drift from the folders past a release, and component pull requests never touch
// README.md (two of them never conflict over it); node tools/build/registry.mjs --readme rewrites it now. The coding
// agents' skill (skills/serupa/SKILL.md) gets the same index as a plain list, at the same times.
import fs from 'node:fs';
import path from 'node:path';

const HERE = path.dirname(new URL(import.meta.url).pathname);
const ROOT = path.resolve(HERE, '..', '..');
const BANNER = '// Generated by tools/build/registry.mjs from the component folders: edit those, not this file.\n';

/** The component folders, A to Z. */
export function components(root = ROOT) {
  const dir = path.join(root, 'src', 'components');
  return fs.readdirSync(dir).filter((n) => fs.statSync(path.join(dir, n)).isDirectory()).sort();
}

/** The components with a stylesheet, in the order they cascade. */
export function cascade(root = ROOT) {
  const listed = fs.readFileSync(path.join(root, 'src', 'styles', 'cascade.txt'), 'utf8').split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
  const styled = components(root).filter((n) => fs.existsSync(path.join(root, 'src', 'components', n, n + '.css')));
  const unknown = listed.filter((n) => !styled.includes(n));
  if (unknown.length) throw new Error(`src/styles/cascade.txt lists ${unknown.join(', ')}, which has no src/components/<Name>/<Name>.css`);
  return [...listed, ...styled.filter((n) => !listed.includes(n))];
}

// A component's status, from the doc comment on its export in <Name>.tsx, so the types carry it to the editor:
// @alpha (still taking shape, may change in any release), @beta (its API may still change in a minor release, said
// in the changeset), @deprecated (going in the next major) or none (stable).
export const STATUSES = ['alpha', 'beta', 'stable', 'deprecated'];
export function status(n, root = ROOT) {
  const file = path.join(root, 'src', 'components', n, `${n}.tsx`);
  if (!fs.existsSync(file)) return 'stable';
  const text = fs.readFileSync(file, 'utf8');
  const at = new RegExp(`^export (?:const|function) ${n}\\b`, 'm').exec(text);
  if (!at) return 'stable';
  // The doc comment that ends on the line just before the export.
  const before = text.slice(0, at.index).trimEnd();
  if (!before.endsWith('*/')) return 'stable';
  const doc = before.slice(before.lastIndexOf('/**'));
  const tags = [...doc.matchAll(/@(alpha|beta|deprecated)\b/g)].map((m) => m[1]);
  if (tags.length > 1) throw new Error(`src/components/${n}/${n}.tsx: its export says @${tags.join(' and @')}; give it one status`);
  return tags[0] ?? 'stable';
}

const write = (file, text) => {
  // Unchanged files keep their timestamp, so a watching Storybook or Vitest doesn't reload for nothing.
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
};

// A string literal in a test file: '…', "…" or `…` (a template's ${…} kept as written).
const STR = "'((?:\\\\.|[^'\\\\])*)'|\"((?:\\\\.|[^\"\\\\])*)\"|`((?:\\\\.|[^`\\\\])*)`";
/** The names of a component's tests, under the describe() they're in, skipped and todo tests left out. */
export function testNames(n, root = ROOT) {
  const file = path.join(root, 'src', 'components', n, `${n}.test.tsx`);
  if (!fs.existsSync(file)) return [];
  const src = fs.readFileSync(file, 'utf8');
  const groups = [];
  const re = new RegExp(String.raw`(?<![\w.])(describe|test|it)(\.only|\.skip|\.todo|\.each\([^)]*\)|\.concurrent)?\(\s*(?:${STR})`, 'g');
  for (const m of src.matchAll(re)) {
    if (m[2] === '.skip' || m[2] === '.todo') continue;
    const name = (m[3] ?? m[4] ?? m[5]).replace(/\\(.)/g, '$1');
    if (m[1] === 'describe') groups.push({ group: name, tests: [] });
    else (groups.at(-1) || groups[groups.push({ group: n, tests: [] }) - 1]).tests.push(name);
  }
  return groups.filter((g) => g.tests.length);
}

export function buildRegistry(root = ROOT) {
  const out = path.join(root, 'src', 'generated');
  const all = components(root);
  const missing = all.filter((n) => !fs.existsSync(path.join(root, 'src', 'components', n, 'index.ts')));
  if (missing.length) throw new Error(`Each component folder needs an index.ts with its public exports: ${missing.join(', ')}`);
  // window.Serupa's type lists each value by name: a `typeof import("./index")` of the package itself breaks the
  // bundled .d.ts. The values are the names in each index.ts's `export { … }` lines (its `export type` lines are types).
  const values = all.map((n) => ({ n, v: [...fs.readFileSync(path.join(root, 'src', 'components', n, 'index.ts'), 'utf8').matchAll(/^export \{([^}]*)\}/gm)].flatMap((m) => m[1].split(',').map((v) => v.trim()).filter(Boolean)) }));
  write(path.join(out, 'components.ts'), BANNER + all.map((n) => `export * from "../components/${n}";\n`).join(''));
  write(path.join(out, 'globals.ts'), BANNER
    + values.filter(({ v }) => v.length).map(({ n, v }) => `import { ${v.join(', ')} } from "../components/${n}";\n`).join('')
    + '\n/** The components on plain pages: window.Serupa (serupa.iife.js) has each of them. */\n'
    + `export interface ComponentGlobals {\n${values.flatMap(({ v }) => v).map((v) => `  ${v}: typeof ${v};\n`).join('')}}\n`);
  write(path.join(out, 'components.css'), `/* ${BANNER.slice(3, -1)} */\n` + cascade(root).map((n) => `@import "../components/${n}/${n}.css";\n`).join(''));
  const worded = all.filter((n) => fs.existsSync(path.join(root, 'src', 'components', n, 'labels.ts')));
  write(path.join(out, 'labels.ts'), BANNER
    + worded.map((n) => `import * as ${n} from "../components/${n}/labels";\n`).join('')
    + '\n/** The words each component brings, from its own labels.ts. */\n'
    + `export type ComponentLabels = ${worded.length ? worded.map((n) => `${n}.${n}Labels`).join(' & ') : '{}'};\n`
    // Object.assign marked pure, not a spread: a bundler keeps a spread it can't prove harmless, which would ship the
    // Indonesian words to every project that never imports idLabels.
    + `export const componentEn: ComponentLabels = /* @__PURE__ */ Object.assign({}, ${worded.map((n) => `${n}.en`).join(', ')});\n`
    + `export const componentId: ComponentLabels = /* @__PURE__ */ Object.assign({}, ${worded.map((n) => `${n}.id`).join(', ')});\n`);
  // For the docs pages too: what each component's tests check, by their names (131).
  write(path.join(root, 'docs', 'generated', 'tested.ts'), BANNER
    + '/** Each component\'s tests by name, in groups as its <Name>.test.tsx has them (describe blocks). */\n'
    + `export const componentTests: Record<string, { group: string; tests: string[] }[]> = ${JSON.stringify(Object.fromEntries(all.map((n) => [n, testNames(n, root)])), null, 1)};\n`);
  // For the docs pages (docs/blocks.tsx), not the package: each component that isn't stable, and its status.
  const unstable = all.map((n) => [n, status(n, root)]).filter(([, st]) => st !== 'stable');
  // In docs/generated/, not src/: nothing in the package reads it.
  fs.mkdirSync(path.join(root, 'docs', 'generated'), { recursive: true });
  write(path.join(root, 'docs', 'generated', 'status.ts'), BANNER
    + '/** Each component that isn\'t stable, by name: alpha, beta or deprecated, from the doc comment on its export. */\n'
    + `export const componentStatus: Record<string, 'alpha' | 'beta' | 'deprecated'> = {${unstable.map(([n, st]) => ` ${n}: '${st}'`).join(',')}${unstable.length ? ' ' : ''}};\n`);
}

const START = '<!-- components:start (written by tools/build/registry.mjs) -->';
const END = '<!-- components:end -->';

/** README.md's components index: a table per Storybook group (A to Z, like its sidebar), one row per component.
 *  With plain, a list per group with no links, for the coding agents' skill (skills/serupa/SKILL.md), which is read away from the repository. */
export function componentIndex(root = ROOT, { plain = false } = {}) {
  const groups = {};
  for (const n of components(root)) {
    const dir = path.join(root, 'src', 'components', n);
    const stories = path.join(dir, `${n}.stories.tsx`);
    const group = fs.existsSync(stories) ? (/title: '(?:Components\/)?([^'/]+)\//.exec(fs.readFileSync(stories, 'utf8')) || [])[1] : undefined;
    const guide = fs.readFileSync(path.join(dir, 'README.md'), 'utf8');
    // The guide's first paragraph after its heading, up to the end of its first sentence.
    const intro = (/^# .*\n+([^\n#`|<-][^\n]*)/m.exec(guide) || [])[1] ?? '';
    // Links between guides (../Combobox/README.md) point from the README instead.
    const sentence = (/^.*?[.!?](?=\s|$)/.exec(intro) || [intro])[0].replace(/[\\|]/g, '\\$&').replace(/\]\(\.\.\//g, '](src/components/');
    const st = status(n, root), mark = st === 'stable' ? '' : ` (${st})`;
    (groups[group ?? 'Other'] ||= []).push(plain ? `- **${n}**${mark}: ${sentence.replace(/\\([\\|])/g, '$1').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')}` : `| [${n}](src/components/${n}/README.md)${mark} | ${sentence} |`);
  }
  return Object.keys(groups).sort((a, b) => Number(a === 'Other') - Number(b === 'Other') || a.localeCompare(b))
    .map((g) => (plain ? `### ${g}\n\n${groups[g].join('\n')}\n` : `### ${g}\n\n| Component | What it's for |\n| --- | --- |\n${groups[g].join('\n')}\n`)).join('\n');
}

/** README.md and the coding agents' skill (skills/serupa/SKILL.md) with their components index rewritten from the component folders. */
export function stampReadme(root = ROOT) {
  for (const [f, plain] of /** @type {[string, boolean][]} */ ([['README.md', false], [path.join('skills', 'serupa', 'SKILL.md'), true]])) {
    const file = path.join(root, f);
    const text = fs.readFileSync(file, 'utf8');
    const a = text.indexOf(START), b = text.indexOf(END);
    if (a < 0 || b < a) throw new Error(`${f} needs the lines ${START} and ${END} around its components index`);
    write(file, text.slice(0, a + START.length) + '\n\n' + componentIndex(root, { plain }) + '\n' + text.slice(b));
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(HERE, 'registry.mjs')) {
  if (process.argv.includes('--readme')) stampReadme(); else buildRegistry();
}
